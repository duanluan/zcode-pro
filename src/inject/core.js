// 注入脚本公共工具：与 helper 通信、DOM 构建、多语言文案。
export const BOOT = typeof window !== 'undefined' ? (window.__ZCODEPRO__ || {}) : {};
export const HELPER_URL = BOOT.helperUrl || 'http://127.0.0.1:47889';

// token/helperUrl 必须在每次调用时实时读 window.__ZCODEPRO__：cli.mjs 重启后 helper 换了
// 随机 token，重新注入会被 index.js 的幂等守卫跳过、页面继续用旧闭包——若在模块求值时
// 固化成常量，旧闭包会永远拿旧 token 报 unauthorized。重注入的 bootstrap 会先更新
// window.__ZCODEPRO__，实时读即可对上新一轮 token。
function liveBoot() {
  return (typeof window !== 'undefined' && window.__ZCODEPRO__) || BOOT;
}

export function rpc(path, options = {}) {
  const boot = liveBoot();
  return fetch((boot.helperUrl || HELPER_URL) + path, {
    method: options.method || 'GET',
    headers: {
      'Content-Type': 'application/json',
      'X-ZCodePro-Token': boot.token || '',
    },
    body: options.body ? JSON.stringify(options.body) : undefined,
  })
    .then((r) => r.json())
    .catch((err) => ({ ok: false, error: String(err && err.message || err) }));
}

// 配置缓存：菜单每次打开时拉取，保证设置弹窗里的开关即时生效
let configCache = { value: null, at: 0 };
export async function getConfig(force = false) {
  const now = Date.now();
  if (!force && configCache.value && now - configCache.at < 3000) return configCache.value;
  const res = await rpc('/config');
  if (res.ok && res.config) {
    configCache = { value: res.config, at: now };
    return res.config;
  }
  return configCache.value || { features: {} };
}
export function clearConfigCache() { configCache = { value: null, at: 0 }; }

// —— ZCode 版本判断（按官方版本启用/停用功能）——
// 版本来源：启动器从 app.asar 读出后写进 bootstrap（window.__ZCODEPRO__.zcodeVersion），
// helper 的 /config 响应也附加同名字段。读不到时为空串，各判断保持旧行为。
export function zcodeAppVersion() {
  const v = liveBoot().zcodeVersion;
  return typeof v === 'string' && v ? v : '';
}

export function zcodeVersionGte(version, major, minor, patch = 0) {
  const m = String(version || '').match(/^(\d+)\.(\d+)\.(\d+)/);
  if (!m) return false;
  const a = Number(m[1]), b = Number(m[2]), c = Number(m[3]);
  return a > major || (a === major && (b > minor || (b === minor && c >= patch)));
}

// 官方“编辑项目”（修改项目名称 + 多文件夹）自 3.16.1 起提供
export function officialRenameSupported() {
  return zcodeVersionGte(zcodeAppVersion(), 3, 16, 1);
}

// 新侧栏检测（3.16.1 起“虚拟项目”重构，workspace-item 系列节点已下线）：
// 版本 >= 3.16.1，或页面出现 section[data-project-id] 项目行（覆盖版本读不到的
// 构建）。一旦命中即记住——同一会话内侧栏不会退回旧结构。
let newSidebarCached = false;
export function isNewProjectSidebar() {
  if (newSidebarCached) return true;
  if (officialRenameSupported()) { newSidebarCached = true; return true; }
  try {
    if (document.querySelector('section[data-project-id]')) { newSidebarCached = true; return true; }
  } catch { /* ignore */ }
  return false;
}

